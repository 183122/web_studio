// Precompiles the JSON Schemas into standalone validator code so the studio
// never needs `new Function` at runtime (keeps a strict CSP without unsafe-eval).
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const definition = JSON.parse(readFileSync(`${root}/schema/app-definition.schema.json`, 'utf8'));
const command = JSON.parse(readFileSync(`${root}/schema/app-command.schema.json`, 'utf8'));

const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
ajv.addSchema(definition);
ajv.addSchema(command);

const code = standaloneCode(ajv, {
  validateAppDefinition: definition.$id,
  validateAppCommand: command.$id,
});
// Inline Ajv's runtime helper so the module is pure ESM (no require()).
const ucs2 = 'function (str) { let n = 0; for (const _ of str) n++; return n; }';
const esm = code.replace('require("ajv/dist/runtime/ucs2length").default', ucs2);
if (/require\(/.test(esm)) throw new Error('generated validator still contains require()');
writeFileSync(`${root}/src/generated/validators.js`, `/* eslint-disable */\n// GENERATED by scripts/compile-validators.mjs — do not edit.\n${esm}\n`);
writeFileSync(
  `${root}/src/generated/validators.d.ts`,
  `import type { ErrorObject } from './ajv-types';\ninterface Fn { (data: unknown): boolean; errors?: ErrorObject[] | null }\nexport declare const validateAppDefinition: Fn;\nexport declare const validateAppCommand: Fn;\n`,
);
writeFileSync(
  `${root}/src/generated/ajv-types.d.ts`,
  `export interface ErrorObject { instancePath: string; keyword: string; message?: string; params: Record<string, unknown> }\n`,
);
console.log('validators generated');
